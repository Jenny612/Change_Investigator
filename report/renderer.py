"""Report renderer — produces Markdown files and rich terminal output."""

from __future__ import annotations

import datetime
from pathlib import Path
from typing import Optional

from models import Report, InvestigationContext


# ---------------------------------------------------------------------------
# Markdown renderer
# ---------------------------------------------------------------------------

_LABEL_MD = {
    "documented": "`[documented]`",
    "inferred from code": "`[inferred from code]`",
    "reconstructed from pattern": "`[reconstructed from pattern]`",
}


def render_markdown(report: Report, ctx: InvestigationContext) -> str:
    pr_ref = f"PR #{report.pr_number}" if report.pr_number else "no PR number"
    synthesis_note = (
        "✅ LLM-synthesised (IBM watsonx Granite)"
        if report.was_synthesised
        else "⚠️  Fallback mode — watsonx not configured or call failed. Evidence-only report."
    )

    lines: list[str] = []

    # Front matter
    lines.append(f"# Change Investigation Report")
    lines.append(f"")
    lines.append(f"| Field | Value |")
    lines.append(f"|-------|-------|")
    lines.append(f"| Commit | `{report.sha[:12]}` |")
    lines.append(f"| PR | {pr_ref} |")
    lines.append(f"| Subject | {report.commit_subject} |")
    lines.append(f"| Author | {ctx.commit.author} |")
    lines.append(f"| Date | {ctx.commit.date} |")
    lines.append(f"| Synthesis | {synthesis_note} |")
    lines.append(f"| Generated | {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')} |")
    lines.append(f"")
    lines.append("---")
    lines.append("")

    # Five sections
    for i, section in enumerate(report.sections, 1):
        lines.append(f"## {i}. {section.title}")
        lines.append("")
        lines.append(section.content)
        lines.append("")
        lines.append("---")
        lines.append("")

    # Evidence appendix
    lines.append("## Appendix: Collected Evidence")
    lines.append("")
    lines.append(f"**Changed files ({len(ctx.diffs)} total):**")
    lines.append("")
    for d in ctx.diffs:
        lines.append(f"- `[{d.status.upper()}/{d.kind.value}]` `{d.path}`")
    lines.append("")

    if ctx.peer_files:
        lines.append("**Structural peers identified:**")
        lines.append("")
        for p in ctx.peer_files:
            lines.append(f"- `{p.path}` — {p.similarity_reason}")
        lines.append("")

    if ctx.sibling_commits:
        lines.append("**Sibling commits (same pattern):**")
        lines.append("")
        for s in ctx.sibling_commits[:8]:
            pr = f" (PR #{s.pr_number})" if s.pr_number else ""
            lines.append(f"- `{s.sha}` — {s.subject}{pr}")
        lines.append("")

    if ctx.changelog_entry:
        lines.append("**Changelog entry:**")
        lines.append("")
        lines.append("```")
        lines.append(ctx.changelog_entry)
        lines.append("```")
        lines.append("")

    if ctx.grep_matches:
        lines.append("**Key symbol references (git grep):**")
        lines.append("")
        for symbol, matches in list(ctx.grep_matches.items())[:6]:
            lines.append(f"- `{symbol}` referenced in {len(matches)} locations")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by Change Investigator — IBM Bob Hackathon*")
    lines.append("")

    return "\n".join(lines)


def save_report(report: Report, ctx: InvestigationContext, output_dir: str) -> Path:
    """Save the Markdown report and return the file path."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    sha_short = report.sha[:8]
    pr_part = f"-{report.pr_number}" if report.pr_number else ""
    filename = f"{sha_short}{pr_part}-report.md"
    path = out / filename

    content = render_markdown(report, ctx)
    path.write_text(content, encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# Terminal renderer (rich)
# ---------------------------------------------------------------------------

def render_terminal(report: Report, ctx: InvestigationContext) -> None:
    """Print a formatted report to the terminal using rich."""
    try:
        from rich.console import Console
        from rich.panel import Panel
        from rich.table import Table
        from rich.text import Text
        from rich.markdown import Markdown
        from rich import box
    except ImportError:
        _render_terminal_plain(report, ctx)
        return

    console = Console()

    # Header
    console.print()
    console.rule("[bold blue]Change Investigator Report[/bold blue]")
    console.print()

    # Metadata table
    meta = Table(box=box.SIMPLE, show_header=False, padding=(0, 1))
    meta.add_column("Field", style="bold cyan", no_wrap=True)
    meta.add_column("Value")
    meta.add_row("Commit", f"[yellow]{report.sha[:12]}[/yellow]")
    meta.add_row("Subject", report.commit_subject)
    if report.pr_number:
        meta.add_row("PR", f"#{report.pr_number}")
    meta.add_row("Author", ctx.commit.author)
    meta.add_row("Date", ctx.commit.date)
    synthesis_label = (
        "[green]LLM-synthesised (watsonx Granite)[/green]"
        if report.was_synthesised
        else "[yellow]Fallback mode (no LLM)[/yellow]"
    )
    meta.add_row("Synthesis", synthesis_label)
    console.print(meta)
    console.print()

    # Five sections
    _section_styles = ["blue", "cyan", "magenta", "green", "yellow"]
    for i, section in enumerate(report.sections):
        colour = _section_styles[i % len(_section_styles)]
        content = _highlight_labels(section.content)
        console.print(Panel(
            Markdown(content),
            title=f"[bold {colour}]{i+1}. {section.title}[/bold {colour}]",
            border_style=colour,
            padding=(1, 2),
        ))
        console.print()

    # Quick stats
    console.rule("[dim]Evidence Summary[/dim]")
    stats = Table(box=box.SIMPLE, show_header=False, padding=(0, 1))
    stats.add_column("", style="dim")
    stats.add_column("")
    stats.add_row("Files changed", str(len(ctx.diffs)))
    stats.add_row("New source files", str(sum(1 for d in ctx.diffs if d.status == "added" and d.kind.value == "source")))
    stats.add_row("Test files", str(len(ctx.test_file_contents)))
    stats.add_row("Structural peers", str(len(ctx.peer_files)))
    stats.add_row("Sibling commits", str(len(ctx.sibling_commits)))
    stats.add_row("Symbol grep results", str(sum(len(v) for v in ctx.grep_matches.values())))
    console.print(stats)
    console.print()


def _highlight_labels(text: str) -> str:
    """Keep label brackets as-is for Markdown rendering."""
    return text


def _render_terminal_plain(report: Report, ctx: InvestigationContext) -> None:
    """Fallback plain-text terminal renderer (no rich)."""
    print("\n" + "=" * 70)
    print("CHANGE INVESTIGATOR REPORT")
    print("=" * 70)
    print(f"Commit: {report.sha[:12]}")
    print(f"Subject: {report.commit_subject}")
    print(f"Synthesis: {'LLM' if report.was_synthesised else 'Fallback (no LLM)'}")
    print()

    for i, section in enumerate(report.sections, 1):
        print(f"\n{i}. {section.title.upper()}")
        print("-" * 40)
        print(section.content)

    print("\n" + "=" * 70)
